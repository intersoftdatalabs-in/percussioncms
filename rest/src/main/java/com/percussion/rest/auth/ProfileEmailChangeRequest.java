package com.percussion.rest.auth;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonRootName;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.xml.bind.annotation.XmlRootElement;

/** Request payload for staging a verified email change on the current account. */
@XmlRootElement(name = "ProfileEmailChangeRequest")
@JsonRootName("ProfileEmailChangeRequest")
@JsonInclude(JsonInclude.Include.NON_NULL)
@Schema(description = "Self-service email change or verification request")
public class ProfileEmailChangeRequest {

  private String email;

  public ProfileEmailChangeRequest() {}

  public ProfileEmailChangeRequest(String email) {
    this.email = email;
  }

  public String getEmail() {
    return email;
  }

  public void setEmail(String email) {
    this.email = email;
  }
}
