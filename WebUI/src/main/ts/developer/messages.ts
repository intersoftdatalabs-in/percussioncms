export type DevMsgKey = keyof typeof DEV_MSG_KEYS;

/**
 * Resolved Developer UI strings for the session locale.
 *
 * <p>Access like {@code DEV_MSG.TITLE} — each property resolves through
 * {@link message} so TMX is used when loaded, otherwise the English segment
 * after {@code @}.
 */
export const DEV_MSG: { readonly [K in DevMsgKey]: string } = new Proxy(DEV_MSG_KEYS, {
  get(target, prop: string | symbol) {
    if (typeof prop !== "string" || !(prop in target)) {
      return undefined;
    }
    return message(target[prop as DevMsgKey]);
  },
}) as { readonly [K in DevMsgKey]: string };
